-- HomeSeek ERD entity USER (Section 5.1 of the SRS). The table is named "users"
-- because USER is a reserved word in PostgreSQL.
CREATE TABLE users (
    user_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(150) NOT NULL,
    password_hash  VARCHAR(255),
    full_name      VARCHAR(100) NOT NULL,
    phone          VARCHAR(20),
    role           VARCHAR(10)  NOT NULL,
    auth_provider  VARCHAR(10)  NOT NULL DEFAULT 'LOCAL',
    google_id      VARCHAR(100),
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT uq_users_google_id UNIQUE (google_id),
    CONSTRAINT ck_users_role CHECK (role IN ('TENANT', 'OWNER', 'ADMIN')),
    CONSTRAINT ck_users_auth_provider CHECK (auth_provider IN ('LOCAL', 'GOOGLE')),
    CONSTRAINT ck_users_local_has_password CHECK (auth_provider <> 'LOCAL' OR password_hash IS NOT NULL)
);

-- Tokens invalidated by logout. A row is only needed until the token's own expiry.
CREATE TABLE revoked_tokens (
    jti         VARCHAR(36) PRIMARY KEY,
    expires_at  TIMESTAMP   NOT NULL
);
CREATE INDEX idx_revoked_tokens_expires_at ON revoked_tokens (expires_at);
